/**
 * cdk-nag (AwsSolutions) acknowledgements. Each one has a written reason;
 * anything not acknowledged here fails synth. Review with the owner before
 * deploy (task 21): several are cost decisions, not technical limits.
 */
import { Token, Validations, type Stack } from 'aws-cdk-lib';
import type { IConstruct } from 'constructs';

function ack(scope: IConstruct, id: string, reason: string): void {
  Validations.of(scope).acknowledge({ id, reason });
}

function child(scope: IConstruct, id: string): IConstruct {
  const found = scope.node.tryFindChild(id);
  if (!found) throw new Error(`nag-suppressions: ${scope.node.path}/${id} not found`);
  return found;
}

/** The singleton Lambda that BucketDeployment adds at stack level (id `Custom::CDKBucketDeployment<uuid>`). */
function bucketDeploymentHandler(site: Stack): IConstruct {
  const found = site.node.children.find((c) => c.node.id.startsWith('Custom::CDKBucketDeployment'));
  if (!found) throw new Error('nag-suppressions: BucketDeployment handler not found');
  return found;
}

export function addNagSuppressions(_proofApi: Stack, site: Stack): void {
  const bucket = child(site, 'SiteBucket');
  ack(
    bucket,
    'AwsSolutions::AwsSolutions-S1',
    'The bucket holds only the public static build and is read solely by this distribution through OAC. ' +
      'Server access logs would need a second bucket and add cost; CloudFront metrics cover the demo. Owner may revisit.',
  );

  const distribution = child(site, 'Site');
  ack(
    distribution,
    'AwsSolutions::AwsSolutions-CFR3',
    'No CloudFront access logs for the demo, to stay inside the USD 10 budget; CloudFront and Lambda metrics plus the ' +
      'proof API JSON logs cover operations. Owner decision: standard logging v2 to CloudWatch Logs can be added.',
  );
  ack(
    distribution,
    'AwsSolutions::AwsSolutions-CFR2',
    'Owner decision: WAF omitted for cost (fixed ~$10/month equals the whole budget). The Function URL is protected by ' +
      'AWS_IAM auth plus a CloudFront-only resource policy; abuse cost is bounded by reserved concurrency.',
  );
  ack(
    distribution,
    'AwsSolutions::AwsSolutions-CFR1',
    'Requirement 8.1: the lab is open to judges anywhere, so no geo restriction.',
  );
  ack(
    distribution,
    'Annotation::@aws-cdk/aws-cloudfront-origins:listBucketSecurityRisk',
    'LIST is granted so missing files return 404 instead of 403. defaultRootObject is index.html and the SPA rewrite ' +
      'function sends "/" to /index.html, and the cache policy forwards no query strings, so viewers cannot list the bucket.',
  );

  const deployer = bucketDeploymentHandler(site);
  ack(
    deployer,
    'AwsSolutions::AwsSolutions-L1',
    'BucketDeployment handler: runtime chosen by aws-cdk-lib (pinned version); runs only during deploys.',
  );
  ack(
    deployer,
    'AwsSolutions::AwsSolutions-IAM4[Policy::arn:<AWS::Partition>:iam::aws:policy/service-role/AWSLambdaBasicExecutionRole]',
    'BucketDeployment handler role created by aws-cdk-lib; the managed policy only allows writing its own logs.',
  );
  // The CDK asset bucket finding is rendered differently with and without a concrete account.
  const assetBucketFindings = Token.isUnresolved(site.account)
    ? [`Resource::arn:aws:s3:::cdk-hnb659fds-assets-<AWS::AccountId>-${site.region}/*`]
    : [
        `Resource::arn:<AWS::Partition>:s3:::cdk-hnb659fds-assets-${site.account}-${site.region}/*`,
        `Resource::arn:aws:s3:::cdk-hnb659fds-assets-${site.account}-${site.region}/*`,
      ];
  for (const finding of [
    'Action::s3:GetBucket*',
    'Action::s3:GetObject*',
    'Action::s3:List*',
    'Action::s3:Abort*',
    'Action::s3:DeleteObject*',
    ...assetBucketFindings,
    'Resource::<SiteBucket397A1860.Arn>/*',
    'Resource::*',
  ]) {
    ack(
      deployer,
      `AwsSolutions::AwsSolutions-IAM5[${finding}]`,
      'BucketDeployment handler role generated by aws-cdk-lib: s3:GetObject*/GetBucket*/List* on the CDK asset bucket, ' +
        's3 read/write/DeleteObject* (prune) on the site bucket only, and cloudfront:CreateInvalidation/GetInvalidation ' +
        'on * (CDK does not scope these to the distribution). Narrowing them means overriding a CDK-owned singleton ' +
        'role. Runs only during deploys.',
    );
  }
}
